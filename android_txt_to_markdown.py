#!/usr/bin/env python3
"""Convert a GilApps SMS Backup & Print Android TXT export into evidence-ready Markdown.

Preserves every message (including reactions, repeated quoted content, and attachment
filenames), chronological order, and original source line references. Does not
interpret screenshots or infer an unknown timezone.

Python 3.9+; standard library only.

Usage:
  python android_txt_to_markdown.py android_darcy_group.txt \
      --me Sam --wife Regina --contact Darcy

Outputs next to input:
  android_darcy_group_messages.md
  android_darcy_group_index.csv

The output is an analysis copy. Retain the unchanged TXT and original attachments.
"""

import argparse
import csv
import hashlib
import re
from collections import Counter
from dataclasses import dataclass
from datetime import datetime
from pathlib import Path
import json
import os
from urllib.parse import quote
from android_html_export import read_export
from output_safety import staged_outputs

SOURCE_TYPE = 'android_sms'
DAY_RE = re.compile(
    r'^-{3,}\s*(Monday|Tuesday|Wednesday|Thursday|Friday|Saturday|Sunday),'
    r'\s*(Jan|Feb|Mar|Apr|May|Jun|Jul|Aug|Sep|Oct|Nov|Dec)'
    r'\s+(\d{1,2}),\s*(\d{4})\s*-{3,}$'
)
MESSAGE_RE = re.compile(r'^(.{1,150}?)\s+\((\d{1,2}:[0-5]\d\s*[AP]M)\)$')
ATTACHMENT_RE = re.compile(r'^\s*\U0001f4c4\s*(.+?)\s*$', re.MULTILINE)
FOOTER = 'Generated by GilApps SMS Backup & Print'


@dataclass
class Message:
    number: int
    sender_original: str
    time_original: str
    local_time: str
    header_line: int
    body_line_start: int
    body_line_end: int
    body: str
    attachment_references: list


def slugify(value: str) -> str:
    result = re.sub(r'[^a-z0-9_-]+', '_', value.lower()).strip('_')
    if not result:
        raise ValueError('Conversation ID must contain letters or digits.')
    return result


def parse_gilapps_text(raw: str):
    lines = raw.splitlines()
    messages = []
    anomalies = []
    active_day = None
    current = None
    message_lines = []
    last_date = None

    def flush():
        nonlocal current, message_lines
        if current is None:
            return
        # Only trim entirely blank outer lines; retain substantive whitespace,
        # paragraph breaks, quoted replies and signatures as written.
        body_lines = list(message_lines)
        while body_lines and not body_lines[0][1].strip():
            body_lines.pop(0)
        while body_lines and not body_lines[-1][1].strip():
            body_lines.pop()
        body = '\n'.join(line for _, line in body_lines)
        if not body:
            anomalies.append(f'Message at source line {current[2]} has no body')
        start = body_lines[0][0] if body_lines else current[2]
        end = body_lines[-1][0] if body_lines else current[2]
        attachments = list(dict.fromkeys(
            match.group(1).strip() for match in ATTACHMENT_RE.finditer(body)
        ))
        messages.append(Message(
            number=len(messages) + 1,
            sender_original=current[0],
            time_original=current[1],
            local_time=current[3],
            header_line=current[2],
            body_line_start=start,
            body_line_end=end,
            body=body,
            attachment_references=attachments,
        ))
        current = None
        message_lines = []

    for line_no, line in enumerate(lines, 1):
        stripped = line.strip()
        date_match = DAY_RE.fullmatch(stripped)
        if date_match:
            flush()
            weekday, month, day, year = date_match.groups()
            active_day = datetime.strptime(f'{month} {int(day)} {year}', '%b %d %Y')
            if active_day.strftime('%A') != weekday:
                anomalies.append(f'Weekday does not match calendar on line {line_no}: {stripped}')
            last_date = line_no
            continue

        if stripped == FOOTER or (not active_day and stripped.startswith('Conversation between ')):
            if stripped == FOOTER:
                flush()
            continue

        head = MESSAGE_RE.fullmatch(stripped)
        if head:
            flush()
            if active_day is None:
                anomalies.append(f'Message found before a dated section at line {line_no}')
                continue
            sender, time_text = head.groups()
            try:
                parsed_time = datetime.strptime(time_text.strip(), '%I:%M %p')
            except ValueError as exc:
                raise ValueError(f'Invalid timestamp at source line {line_no}: {time_text}') from exc
            local_dt = active_day.replace(hour=parsed_time.hour, minute=parsed_time.minute)
            current = (sender, time_text, line_no, local_dt.strftime('%Y-%m-%d %H:%M'))
            continue

        if current is not None:
            message_lines.append((line_no, line))
        elif stripped:
            anomalies.append(f'Unassigned text at line {line_no}: {stripped[:140]}')

    flush()
    if not messages:
        raise ValueError('No GilApps message headers found. Expected: Me (12:29 PM).')
    # Guard against unexpected skips or merged messages before writing results.
    header_count = sum(bool(MESSAGE_RE.fullmatch(line.strip())) for line in lines)
    if len(messages) != header_count:
        anomalies.append(f'Parsed {len(messages)} of {header_count} apparent message headers')
    return messages, anomalies


def main():
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('txt', type=Path, help='Android GilApps TXT or HTML export')
    parser.add_argument('--me', default='Sam', help='Name to use for source speaker "Me"')
    parser.add_argument('--wife', default='Regina', help='Name to use for source speaker "Wife"')
    parser.add_argument('--contact', default='Darcy', help='Name to use for external contact')
    parser.add_argument('--contact-label', default='Darcy Real estate',
                        help='Name of external contact as printed in TXT')
    parser.add_argument('--conversation-id', default=None,
                        help='Permanent ID across reruns; default is TXT filename stem')
    parser.add_argument('--output', type=Path, help='Output Markdown path')
    parser.add_argument('--index', type=Path, help='Output CSV index path')
    args = parser.parse_args()

    source = args.txt.expanduser().resolve()
    if not source.is_file():
        parser.error(f'Input file not found: {source}')
    raw_bytes = source.read_bytes()
    try:
        raw = raw_bytes.decode('utf-8-sig')
    except UnicodeDecodeError as exc:
        parser.error(f'The TXT is not UTF-8 encoded: {exc}')
    source_sha256 = hashlib.sha256(raw_bytes).hexdigest()
    conversation_id = slugify(args.conversation_id or source.stem)
    output = (args.output or source.with_name(source.stem + '_messages.md')).expanduser().resolve()
    index = (args.index or source.with_name(source.stem + '_index.csv')).expanduser().resolve()
    if source in (output, index) or output == index:
        parser.error('Output paths must be distinct from each other and the original TXT')
    output.parent.mkdir(parents=True, exist_ok=True)
    index.parent.mkdir(parents=True, exist_ok=True)

    is_html = source.suffix.lower() == '.html'
    if is_html:
        messages, anomalies, files_by_message = read_export(raw, source, parse_gilapps_text)
    else:
        messages, anomalies = parse_gilapps_text(raw)
        files_by_message = {}
    sender_map = {'Me': args.me, 'Wife': args.wife, args.contact_label: args.contact}
    unknown = sorted(set(m.sender_original for m in messages) - set(sender_map))
    if unknown:
        parser.error('Unknown speaker labels: ' + ', '.join(unknown) +
                     '. Edit the sender map or pass --contact-label.')

    participants = list(dict.fromkeys((args.me, args.wife, args.contact)))
    all_participants = ', '.join(participants)
    header = [
        f'# Android SMS archive — {args.contact} group', '',
        f'**Source type:** `{SOURCE_TYPE}`',
        f'**Source {"HTML" if is_html else "TXT"}:** `{source.name}`',
        f'**Source SHA-256:** `{source_sha256}`',
        f'**Conversation ID:** `{SOURCE_TYPE}:{conversation_id}`',
        f'**Messages represented:** {len(messages)}',
        f'**Conversation:** Group chat: {all_participants}',
        '**Order:** Original GilApps export order, oldest first',
        '**Time zone:** Not specified in TXT; local displayed time, NOT UTC',
        '**Time precision:** Minute; repeated times may represent distinct messages',
        '**Attachments:** Filename references only; original photos/files are not included in TXT',
        '**Evidence note:** Messages, reactions, and quoted replies are preserved; no deduplication.',
        '**Provenance:** Retain original TXT and original attachments; source line numbers point to this TXT.',
        '',
    ]
    csv_rows = []
    if is_html:
        header = [line.replace('Not specified in TXT', 'Not specified in HTML')
                  .replace('Filename references only; original photos/files are not included in TXT', 'Local files linked from the HTML export; unavailable files are labeled')
                  .replace('Retain original TXT and original attachments; source line numbers point to this TXT.', 'Retain the original HTML, smsbackup, and attachment folder; line references point to the HTML.') for line in header]
    for msg in messages:
        sender = sender_map[msg.sender_original]
        others = ', '.join(person for person in participants if person != sender)
        source_id = f'{SOURCE_TYPE}:{conversation_id}:{msg.number:04d}'
        message_type = ('attachment_reference' if msg.attachment_references and
                        not re.sub(r'\s+', '', ATTACHMENT_RE.sub('', msg.body)) else
                        'reaction' if re.match(r'^[\u200b\u200a\u2009\ufeff\u2060\u202f\u200c\u200d\u00a0\s]*[^\w\n]{1,12}\s*to\s*[“\"]', msg.body, re.UNICODE) else
                        'message')
        header.extend([
            '---', '',
            f'## Message {msg.number:04d} — {msg.local_time}',
            f'**From:** {sender}  ',
            f'**To:** {others} (group)  ',
            f'**Source type:** `{SOURCE_TYPE}`  ',
            f'**Source ID:** `{source_id}`  ',
            f'**Source:** {"HTML" if is_html else "TXT"} lines {msg.header_line}–{msg.body_line_end}',
        ])
        if msg.attachment_references:
            header.append('**Attachment references:** ' + ' | '.join(msg.attachment_references))
        files = files_by_message.get(msg.number, [])
        for item in files:
            item['relative_path'] = Path(os.path.relpath(source.parent / item['relative_path'], output.parent)).as_posix()
        if files:
            header.append('**Attachment files:** ' + ' · '.join(
                '[' + re.sub(r'[\[\]\r\n]', '_', item['original_filename']) + '](' + quote(item['relative_path'], safe='/') + ')' + ('' if item['available'] else ' [unavailable]') for item in files))
        header.extend(['', msg.body, ''])
        csv_rows.append({
            'source_id': source_id,
            'source_type': SOURCE_TYPE,
            'source_file': source.name,
            'conversation_id': conversation_id,
            'message_number': msg.number,
            'datetime_no_timezone': msg.local_time,
            'timestamp_as_printed': msg.time_original,
            'sender': sender,
            'sender_original': msg.sender_original,
            'recipients_group': others,
            'message_type': message_type,
            'source_header_line': msg.header_line,
            'source_body_start_line': msg.body_line_start,
            'source_end_line': msg.body_line_end,
            'attachment_references': ' | '.join(msg.attachment_references),
            'body_chars': len(msg.body),
            'body_sha256': hashlib.sha256(msg.body.encode('utf-8')).hexdigest(),
            'body_preview': ' '.join(msg.body.split())[:170],
            'attachment_files_json': json.dumps(files, ensure_ascii=False),
        })

    # Refuse to silently deliver an incomplete archive.
    if anomalies:
        for a in anomalies:
            print('WARNING:', a)
        parser.error('Found anomalies in the export. No output written; review source TXT.')
    with staged_outputs([output, index]) as stages:
        stages[0].write_text('\n'.join(header), encoding='utf-8')
        with stages[1].open('w', encoding='utf-8-sig', newline='') as f:
            writer = csv.DictWriter(f, fieldnames=list(csv_rows[0]))
            writer.writeheader()
            writer.writerows(csv_rows)

    print('Original source:', source)
    print('Source type:', SOURCE_TYPE)
    print('Source SHA256:', source_sha256)
    print('Messages:', len(messages), 'dates:', len(set(m.local_time[:10] for m in messages)))
    print('Speakers:', dict(Counter(row['sender'] for row in csv_rows)))
    print('Messages with attachment references:', sum(bool(m.attachment_references) for m in messages))
    print('Markdown:', output, f'({output.stat().st_size:,} bytes)')
    print('Index CSV:', index, f'({index.stat().st_size:,} bytes)')


if __name__ == '__main__':
    main()
